#!/usr/bin/env python3
"""
Validate tango-python SDK against the canonical API filter/shape manifest.

This script reads the API contract (generated by tango, vendored at
contracts/filter_shape_contract.json, refreshed via scripts/refresh_contract.py)
and checks that the SDK methods conform to it. The SDK owns the mapping of
resources to methods and the parameter name translations.

Conformance checks:
1. Coverage: every runtime filter param in the contract is exposed by the
   mapped SDK method (explicit argument or via `api_param_mapping`). Missing
   params are errors unless accepted in contracts/conformance_baseline.json
   (then warnings — a tracked backlog, not silent drift).
2. Staleness: every filter-like SDK argument resolves to a param the API
   actually accepts. A stale param silently no-ops for users, so this is
   always an error.
3. Types: when the contract carries type metadata (schema_version >= 2), each
   SDK argument's annotation must be compatible with the contract value type.
4. Shapes: every ShapeConfig constant parses and validates against the SDK
   schema for its model (so default shapes only reference allowed fields).

Usage:
    uv run python scripts/check_filter_shape_conformance.py
    uv run python scripts/check_filter_shape_conformance.py --manifest path/to/contract.json
    uv run python scripts/check_filter_shape_conformance.py --suggest
"""

from __future__ import annotations

import argparse
import ast
import json
from pathlib import Path
from typing import Any

REPO_ROOT = Path(__file__).resolve().parents[1]
CLIENT_PATH = REPO_ROOT / "tango" / "client.py"
DEFAULT_MANIFEST_PATH = REPO_ROOT / "contracts" / "filter_shape_contract.json"
BASELINE_PATH = REPO_ROOT / "contracts" / "conformance_baseline.json"


# ---------------------------------------------------------------------------
# Resource → SDK method mapping
# ---------------------------------------------------------------------------
# The SDK decides which method handles which API resources. This mapping is
# owned by tango-python, not inferred by the API.

RESOURCE_TO_METHOD: dict[str, str | None] = {
    # list_* methods
    "contracts": "list_contracts",
    "idvs": "list_idvs",
    "vehicles": "list_vehicles",
    "otas": "list_otas",
    "otidvs": "list_otidvs",
    "subawards": "list_subawards",
    "organizations": "list_organizations",
    "opportunities": "list_opportunities",
    "notices": "list_notices",
    "forecasts": "list_forecasts",
    "grants": "list_grants",
    "entities": "list_entities",
    "agencies": "list_agencies",
    "naics": "list_naics",
    "gsa_elibrary_contracts": "list_gsa_elibrary_contracts",
    "itdashboard": "list_itdashboard_investments",
    # Nested routes are keyed with a slash in the contract ("budget/accounts").
    # The pre-slash key is kept so an older vendored contract still maps.
    "budget/accounts": "list_budget_accounts",
    "budget_accounts": "list_budget_accounts",
    "dibbs/rfqs": "list_dibbs_rfqs",
    "dibbs/rfps": "list_dibbs_rfps",
    "dibbs/awards": "list_dibbs_awards",
    "exclusions": "list_exclusions",
    "sbir/topics": "list_sbir_topics",
    "sbir/solicitations": "list_sbir_solicitations",
    # Resources not yet implemented in SDK
    "offices": None,
}

# Params the API genuinely accepts but the contract omits, so they would read as
# stale (a silent no-op) when they in fact work. Tango surfaces view-handled
# search params for filtersets that declare `min_length_params`; where it does
# not, the param is absent from the contract even though the endpoint honors it.
# Each entry must be verified against the live API before being added, and
# removed once Tango's contract generator surfaces it.
#   budget/accounts `search`: verified 2026-07-19 — 21,170 results unfiltered vs
#   0 for a nonsense term, so the endpoint clearly applies it.
CONTRACT_OMITTED_PARAMS: dict[str, frozenset[str]] = {
    "budget/accounts": frozenset({"search"}),
}

# SDK-level conveniences that never correspond to API filter params.
# `sort`/`order` compose into the API's `ordering`; `filters` is the legacy
# SearchFilters escape hatch; the rest are pagination/shaping controls.
NON_FILTER_ARGS = {
    "cursor",
    "limit",
    "page",
    "shape",
    "flat",
    "flat_lists",
    "joiner",
    "filters",
    "sort",
    "order",
    "verbose",
}

# Contract value type → acceptable Python annotation base types.
# Dates/datetimes are passed as ISO strings in this SDK; numbers are accepted
# as int, float, or string (amounts are conventionally strings). `string` is
# the contract's catch-all (custom API filters often subclass CharFilter for
# numeric/boolean semantics), so it does not constrain the SDK annotation.
TYPE_COMPAT: dict[str, set[str] | None] = {
    "string": None,
    "choice": {"str"},
    "ordering": {"str"},
    "date": {"str"},
    "datetime": {"str"},
    "time": {"str"},
    "number": {"int", "float", "str"},
    "boolean": {"bool"},
}

# Contract value type → suggested annotation for --suggest scaffolds.
SUGGESTED_ANNOTATION: dict[str, str] = {
    "string": "str | None",
    "choice": "str | None",
    "ordering": "str | None",
    "date": "str | None",
    "datetime": "str | None",
    "time": "str | None",
    "number": "str | None",
    "boolean": "bool | None",
}


